// Production build → dist/ (what Render's static site publishes).
//
//   1. Tailwind compiled + minified          → dist/css/tailwind.css
//   2. ES modules copied as-is (no bundler)  → dist/js/**
//   3. env.js generated from env vars        → dist/js/env.js
//        API_BASE_URL  full URL of the API, e.g. https://math3d-api.onrender.com
//   4. index.html with cache-busting ?v=<commit> on the entry CSS/JS
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, buildCss } from './tailwind.mjs';

const DIST = join(ROOT, 'dist');
const version = (process.env.RENDER_GIT_COMMIT || Date.now().toString(36)).slice(0, 12);

function resolveApiBase() {
  const raw = (process.env.API_BASE_URL || '').trim().replace(/\/+$/, '');
  if (!raw) {
    console.warn('⚠️  API_BASE_URL is not set — the app will use PRODUCTION_API_FALLBACK from js/config.js.');
    return '';
  }
  let url;
  try { url = new URL(raw); } catch { console.error(`✖ API_BASE_URL is not a valid URL: "${raw}"`); process.exit(1); }
  const local = ['localhost', '127.0.0.1'].includes(url.hostname);
  if (url.protocol !== 'https:' && !local) {
    console.error(`✖ API_BASE_URL must use https:// in production (got "${raw}").`);
    process.exit(1);
  }
  return `${url.origin}${url.pathname.replace(/\/+$/, '')}`;
}

const apiBase = resolveApiBase();

rmSync(DIST, { recursive: true, force: true });
mkdirSync(join(DIST, 'css'), { recursive: true });

buildCss('dist/css/tailwind.css', { minify: true });
cpSync(join(ROOT, 'js'), join(DIST, 'js'), { recursive: true });

writeFileSync(join(DIST, 'js', 'env.js'), `// Generated by scripts/build.mjs — do not edit.
export const ENV = Object.freeze({
  API_BASE_URL: ${JSON.stringify(apiBase)},
  BUILD: ${JSON.stringify(version)},
});
`);

const html = readFileSync(join(ROOT, 'index.html'), 'utf8')
  .replace('href="./css/tailwind.css"', `href="./css/tailwind.css?v=${version}"`)
  .replace('src="./js/game.js"', `src="./js/game.js?v=${version}"`);
writeFileSync(join(DIST, 'index.html'), html);

console.log(`✔ Built dist/ (version ${version})`);
console.log(`  API_BASE_URL → ${apiBase || '(fallback in js/config.js)'}`);
